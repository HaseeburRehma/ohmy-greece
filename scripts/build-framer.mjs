// Builds framer/dist/OMGFranchise.tsx: one self-contained Framer code file with the franchise
// page sections, their CSS and the property controls. Paste it into the Framer code file
// "OMGFranchise" after changing a section (see README, "Framer").
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import * as esbuild from "esbuild";

const read = (p) => readFileSync(p, "utf8");

// 1. Tailwind for the sections: theme + utilities only (no preflight, which would restyle the Framer site).
const globals = read("src/app/globals.css")
  .replace('@import "tailwindcss";', "")
  .replace(/@font-face\s*{[^}]*Fineday[^}]*}/, "")
  .replace(/html\s*{[^}]*}/, "")
  .replace(/html\.lenis\s*{[^}]*}/, "")
  .replace(/body\s*{[^}]*}/, "")
  .replace(/html\s*{\s*scroll-behavior: auto;\s*}/, "");
writeFileSync(
  "framer/omg.src.css",
  `@import "tailwindcss/theme.css" layer(theme);\n@import "tailwindcss/utilities.css" layer(utilities);\n@source "../src/components";\n@source "./";\n${globals}`,
);
execFileSync("node_modules/.bin/tailwindcss", ["-i", "framer/omg.src.css", "-o", "framer/omg.raw.css"], { stdio: "inherit" });

// 2. Unwrap @layer blocks: Framer's own CSS is unlayered and would otherwise win every tie.
function unlayer(css) {
  let out = css.replace(/@layer [\w\s,]+;/g, "");
  for (let i = out.indexOf("@layer "); i !== -1; i = out.indexOf("@layer ")) {
    const open = out.indexOf("{", i);
    let depth = 1, j = open + 1;
    for (; depth && j < out.length; j++) depth += out[j] === "{" ? 1 : out[j] === "}" ? -1 : 0;
    out = out.slice(0, i) + out.slice(open + 1, j - 1) + out.slice(j);
  }
  return out;
}

// 3. Breakpoints follow the component's width, not the window: on the Framer canvas every
//    breakpoint frame lives in the same window, so media queries would all look like desktop.
const responsive = (css) => css.replace(/@media \((width [<>]=? [\d.]+(?:rem|px))\)/g, "@container omg ($1)");

const FINEDAY = "https://framerusercontent.com/assets/ESSRLwcvLbTtOUtmbDPxOp03LIY.woff2";
const base = `@import url("https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Oswald:wght@500;600;700&family=Rubik:wght@500;600&display=swap");
@font-face { font-family: "Fineday-StyleTwo"; src: url("${FINEDAY}") format("woff2"); font-display: swap; }
.omg {
  container: omg / inline-size;
  width: 100%;
  --font-inter: "Inter", "Inter Placeholder", system-ui, sans-serif;
  --font-oswald: "Oswald", "Oswald Placeholder", sans-serif;
  --font-rubik: "Rubik", sans-serif;
  --font-kaushan: "Fineday-StyleTwo", "Kaushan Script", cursive;
  font-family: var(--font-inter);
  color: #3b001b;
  line-height: 1.5;
  -webkit-font-smoothing: antialiased;
  text-align: left;
}
:where(.omg) *, :where(.omg) ::before, :where(.omg) ::after { box-sizing: border-box; margin: 0; padding: 0; border: 0 solid; }
:where(.omg) :is(h1, h2, h3, h4, h5, h6) { font-size: inherit; font-weight: inherit; }
:where(.omg) :is(ol, ul) { list-style: none; }
:where(.omg) a { color: inherit; text-decoration: inherit; }
:where(.omg) :is(img, svg, video) { display: block; vertical-align: middle; }
:where(.omg) :is(img, video) { max-width: 100%; height: auto; }
:where(.omg) :is(button, input, select, textarea) { font: inherit; color: inherit; background-color: transparent; border-radius: 0; letter-spacing: inherit; }
:where(.omg) :is(button, [role="button"]) { cursor: pointer; }
:where(.omg) [hidden]:where(:not([hidden="until-found"])) { display: none !important; }
`;
const css = (await esbuild.transform(base + responsive(unlayer(read("framer/omg.raw.css"))), { loader: "css", minify: true })).code;
writeFileSync("framer/omg.generated.css", css);
writeFileSync("framer/omg-css.generated.ts", `// GENERATED by scripts/build-framer.mjs\nexport default ${JSON.stringify(css)};\n`);

// 4. Bundle the sections. React and the framer package come from Framer itself.
const result = await esbuild.build({
  entryPoints: ["framer/entry.tsx"],
  bundle: true,
  write: false,
  format: "esm",
  jsx: "automatic",
  target: "es2020",
  minifyWhitespace: true,
  minifySyntax: true,
  external: ["react", "react-dom", "react/jsx-runtime", "framer"],
  alias: { "next/image": "./framer/next-image.tsx" },
  loader: { ".css": "text" },
  logOverride: { "module-level-directive": "silent" },
});
let code = result.outputFiles[0].text;
const exportMatch = code.match(/export\s*{([^}]*)};?\s*$/);
if (!exportMatch) throw new Error("bundle export not found");
const names = Object.fromEntries(
  exportMatch[1].split(",").map((part) => {
    const [local, exported = local] = part.trim().split(/\s+as\s+/);
    return [exported.trim(), local.trim()];
  }),
);
code = code.slice(0, exportMatch.index);

const out = `// @ts-nocheck -- bundled JavaScript; the typed source is framer/entry.tsx
// Oh My Greece – Franchise page sections. GENERATED by scripts/build-framer.mjs from
// github.com/HaseeburRehma/ohmy-greece; edit the repo and rebuild rather than this file.
// Texts, lists, photos and the film are editable in the properties panel.
import { addPropertyControls } from "framer";
${code}
/**
 * @framerSupportedLayoutWidth any-prefer-fixed
 * @framerSupportedLayoutHeight auto
 * @framerIntrinsicWidth 1440
 */
export default function OMGFranchisePage(props) {
  return ${names.OMGFranchise}(props);
}
addPropertyControls(OMGFranchisePage, ${names.CONTROLS});
`;
mkdirSync("framer/dist", { recursive: true });
writeFileSync("framer/dist/OMGFranchise.tsx", out);
console.log(`framer/dist/OMGFranchise.tsx: ${(out.length / 1024).toFixed(0)} KB (CSS ${(css.length / 1024).toFixed(0)} KB)`);
